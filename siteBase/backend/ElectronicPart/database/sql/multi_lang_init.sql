-- -----------------------------------------------------------
-- 1. 语言类型表 sk_lang_type
-- -----------------------------------------------------------
DROP TABLE IF EXISTS `sk_lang_type`;
CREATE TABLE `sk_lang_type` (
  `id` int(11) NOT NULL AUTO_INCREMENT,
  `language_name` varchar(50) NOT NULL DEFAULT '' COMMENT '语言名称',
  `file_name` varchar(20) DEFAULT '' COMMENT '配置文件名称(如zh-CN)',
  `status` tinyint(1) NOT NULL DEFAULT '0' COMMENT '1启用0禁用',
  `is_default` tinyint(1) NOT NULL DEFAULT '0' COMMENT '是否默认语言',
  `is_del` tinyint(1) NOT NULL DEFAULT '0' COMMENT '是否删除',
  `create_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `update_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='语言类型';

