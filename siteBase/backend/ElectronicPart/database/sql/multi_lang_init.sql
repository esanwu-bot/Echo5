-- -----------------------------------------------------------
-- 2. 语言码表 sk_lang_code（核心翻译存储）
-- -----------------------------------------------------------
DROP TABLE IF EXISTS `sk_lang_code`;
CREATE TABLE `sk_lang_code` (
  `id` int(11) NOT NULL AUTO_INCREMENT,
  `type_id` int(11) NOT NULL DEFAULT '0' COMMENT '语言类型(FK→sk_lang_type.id)',
  `code` varchar(255) NOT NULL DEFAULT '' COMMENT '状态码(编号)',
  `remarks` varchar(255) NOT NULL DEFAULT '' COMMENT '中文备注标识(作为翻译key)',
  `lang_explain` varchar(255) NOT NULL DEFAULT '' COMMENT '翻译文本',
  `is_admin` tinyint(1) NOT NULL DEFAULT '0' COMMENT '1=管理后台 2=用户前端',
  `create_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `update_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_type_id` (`type_id`),
  KEY `idx_code` (`code`),
  KEY `idx_remarks` (`remarks`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='语言码表';

